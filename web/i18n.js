// t(key) returns the text for the current language, falling back to English.
function currentLang() {
  try {
    const saved = localStorage.getItem('bleat_lang');
    if (saved && I18N[saved]) return saved;
  } catch (_) {}
  return 'en';
}
function t(key) {
  const lang = currentLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}
function setLang(code) {
  try { localStorage.setItem('bleat_lang', code); } catch (_) {}
  location.reload();
}
// Fill every element with data-i18n (text) or data-i18n-ph (placeholder).
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.documentElement.lang = currentLang();
}
function languageSelect() {
  const sel = document.createElement('select');
  sel.setAttribute('aria-label', t('language'));
  sel.style.width = 'auto';
  for (const l of I18N_LANGS) {
    const o = document.createElement('option');
    o.value = l.code; o.textContent = l.label; o.selected = l.code === currentLang();
    sel.appendChild(o);
  }
  sel.addEventListener('change', () => setLang(sel.value));
  return sel;
}
